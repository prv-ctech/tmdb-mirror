CREATE TABLE search.search_documents (
    title_id bigint NOT NULL REFERENCES catalog.titles (id) ON DELETE CASCADE,
    locale text NOT NULL DEFAULT '',
    title text,
    original_title text,
    aliases text NOT NULL DEFAULT '',
    overview text,
    normalized_title text NOT NULL DEFAULT '',
    normalized_original_title text NOT NULL DEFAULT '',
    normalized_aliases text NOT NULL DEFAULT '',
    search_vector tsvector NOT NULL DEFAULT ''::tsvector,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT search_documents_pkey PRIMARY KEY (title_id, locale),
    CONSTRAINT search_documents_locale_check
        CHECK (locale = btrim(locale) AND char_length(locale) <= 16)
);

CREATE OR REPLACE FUNCTION search.refresh_search_document()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, search
AS $function$
BEGIN
    NEW.normalized_title := lower(public.unaccent(coalesce(NEW.title, '')));
    NEW.normalized_original_title := lower(public.unaccent(coalesce(NEW.original_title, '')));
    NEW.normalized_aliases := lower(public.unaccent(coalesce(NEW.aliases, '')));
    NEW.search_vector :=
        setweight(to_tsvector('simple', public.unaccent(coalesce(NEW.title, ''))), 'A')
        || setweight(
            to_tsvector('simple', public.unaccent(coalesce(NEW.original_title, ''))),
            'A'
        )
        || setweight(to_tsvector('simple', public.unaccent(coalesce(NEW.aliases, ''))), 'B')
        || setweight(to_tsvector('simple', public.unaccent(coalesce(NEW.overview, ''))), 'C');
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END
$function$;

ALTER FUNCTION search.refresh_search_document() OWNER TO migrator;
REVOKE ALL ON FUNCTION search.refresh_search_document() FROM PUBLIC;

CREATE TRIGGER search_documents_refresh_vector
BEFORE INSERT OR UPDATE OF title, original_title, aliases, overview
ON search.search_documents
FOR EACH ROW EXECUTE FUNCTION search.refresh_search_document();

CREATE OR REPLACE FUNCTION catalog.sync_search_document()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, catalog, search
AS $function$
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM search.search_documents WHERE title_id = OLD.id;
        RETURN OLD;
    END IF;

    INSERT INTO search.search_documents (
        title_id, locale, title, original_title, overview
    ) VALUES (
        NEW.id, '', NEW.display_title, NEW.original_title, NEW.overview
    )
    ON CONFLICT (title_id, locale) DO UPDATE SET
        title = EXCLUDED.title,
        original_title = EXCLUDED.original_title,
        overview = EXCLUDED.overview;
    RETURN NEW;
END
$function$;

ALTER FUNCTION catalog.sync_search_document() OWNER TO migrator;
REVOKE ALL ON FUNCTION catalog.sync_search_document() FROM PUBLIC;

CREATE TRIGGER titles_sync_search_document
AFTER INSERT OR UPDATE OF display_title, original_title, overview OR DELETE
ON catalog.titles
FOR EACH ROW EXECUTE FUNCTION catalog.sync_search_document();

-- Relationship indexes are title-first through each primary key and dimension-first
-- for facet filters.  Public list indexes are partial because all ordinary routes
-- exclude inactive and anime titles; the paired anime index powers the anime route.
CREATE INDEX titles_non_anime_popularity_idx
    ON catalog.titles (
        media_type,
        (coalesce(popularity, 0::double precision)) DESC,
        id DESC
    )
    WHERE active AND NOT is_anime;
CREATE INDEX titles_anime_popularity_idx
    ON catalog.titles (
        media_type,
        (coalesce(popularity, 0::double precision)) DESC,
        id DESC
    )
    WHERE active AND is_anime;
CREATE INDEX titles_non_anime_release_idx
    ON catalog.titles (media_type, release_date DESC NULLS LAST, id DESC)
    WHERE active AND NOT is_anime;

CREATE INDEX title_genres_genre_idx ON catalog.title_genres (genre_id, title_id);
