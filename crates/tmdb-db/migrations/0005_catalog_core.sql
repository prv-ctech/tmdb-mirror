-- Shared catalog identity, dimensions, relationships, and the first search-ready
-- projection.  This migration deliberately stops before seasons, people/credits,
-- classification history, translations, and image/source tables; those are separate
-- follow-up migrations so each rollout remains reviewable and reversible.

-- pg_trgm and unaccent are trusted extensions on the supported PostgreSQL 18 image.
-- The development bootstrap installs them, while this idempotent guard also lets the
-- SQLx test database be migrated from a clean template.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE catalog.titles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_type text NOT NULL,
    tmdb_id bigint NOT NULL,
    display_title text,
    original_title text,
    overview text,
    tagline text,
    status text,
    original_language text,
    release_date date,
    first_air_date date,
    last_air_date date,
    popularity double precision,
    vote_average double precision,
    vote_count bigint,
    runtime_minutes integer,
    adult boolean NOT NULL DEFAULT false,
    video boolean NOT NULL DEFAULT false,
    homepage text,
    poster_path text,
    backdrop_path text,
    is_anime boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    source_updated_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT titles_media_type_check CHECK (media_type IN ('movie', 'tv')),
    CONSTRAINT titles_tmdb_id_check CHECK (tmdb_id > 0),
    CONSTRAINT titles_original_language_check
        CHECK (original_language IS NULL OR char_length(original_language) BETWEEN 1 AND 16),
    CONSTRAINT titles_popularity_check CHECK (popularity IS NULL OR popularity >= 0),
    CONSTRAINT titles_vote_average_check
        CHECK (vote_average IS NULL OR vote_average BETWEEN 0 AND 10),
    CONSTRAINT titles_vote_count_check CHECK (vote_count IS NULL OR vote_count >= 0),
    CONSTRAINT titles_runtime_check CHECK (runtime_minutes IS NULL OR runtime_minutes >= 0),
    CONSTRAINT titles_identity_unique UNIQUE (media_type, tmdb_id),
    CONSTRAINT titles_id_media_type_unique UNIQUE (id, media_type)
);

